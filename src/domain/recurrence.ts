/* Rule builder for the editor UI                                       */
/* ------------------------------------------------------------------ */

export type Freq = 'daily' | 'weekly' | 'monthly' | 'yearly';
export type EndMode = 'never' | 'until' | 'count';

export interface RecurrenceForm {
  freq: Freq;
  interval: number;
  /** 0 = Monday ... 6 = Sunday (rrule weekday numbering). */
  weekdays: number[];
  endMode: EndMode;
  until?: string; // YYYY-MM-DD, inclusive
  count?: number;
}

const FREQ_MAP: Record<Freq, number> = {
  daily: RRule.DAILY,
  weekly: RRule.WEEKLY,
  monthly: RRule.MONTHLY,
  yearly: RRule.YEARLY,
};
const WEEKDAYS: Weekday[] = [RRule.MO, RRule.TU, RRule.WE, RRule.TH, RRule.FR, RRule.SA, RRule.SU];

export function buildRRule(form: RecurrenceForm): string {
  const opts: Partial<Options> = { freq: FREQ_MAP[form.freq], interval: Math.max(1, form.interval || 1) };
  if (form.freq === 'weekly' && form.weekdays.length) {
    opts.byweekday = [...form.weekdays].sort().map((d) => WEEKDAYS[d]);
  }
  if (form.endMode === 'until' && form.until) {
    const [y, m, d] = form.until.split('-').map(Number);
    opts.until = new Date(Date.UTC(y, m - 1, d, 23, 59, 59)); // floating, end of that day
  } else if (form.endMode === 'count' && form.count) {
    opts.count = Math.max(1, form.count);
  }
  return stripRulePrefix(RRule.optionsToString(opts));
}

export function parseRRule(rrule: string): RecurrenceForm {
  const o = RRule.parseString(stripRulePrefix(rrule));
  const freq = (Object.keys(FREQ_MAP) as Freq[]).find((k) => FREQ_MAP[k] === o.freq) ?? 'weekly';
  const wd = o.byweekday;
  const weekdays = (Array.isArray(wd) ? wd : wd != null ? [wd] : []).map((w) =>
    typeof w === 'number' ? w : typeof w === 'string' ? WEEKDAYS.findIndex((x) => x.toString() === w) : w.weekday,
  );
  const form: RecurrenceForm = { freq, interval: o.interval ?? 1, weekdays, endMode: 'never' };
  if (o.until) {
    form.endMode = 'until';
    form.until = o.until.toISOString().slice(0, 10);
  } else if (o.count) {
    form.endMode = 'count';
    form.count = o.count;
  }
  return form;
}

export function describeRRule(rrule: string): string {
  try {
    const text = RRule.fromString(stripRulePrefix(rrule)).toText();
    return text.charAt(0).toUpperCase() + text.slice(1);
  } catch {
    return 'Repeats';
  }
}

