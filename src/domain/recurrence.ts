import { RRule, type Options, type Weekday } from 'rrule';
import type { Completion, Item, Override } from '../db/schema';

/*
 * rrule computes in UTC. To keep wall-clock times stable across DST changes
 * (gym stays at 18:00 in summer and winter) we work in "floating" time: a
 * local date-time is encoded as a UTC Date with the same components, expanded,
 * and decoded back to local time.
 */
export function toFloating(d: Date): Date {
  return new Date(
    Date.UTC(d.getFullYear(), d.getMonth(), d.getDate(), d.getHours(), d.getMinutes(), d.getSeconds()),
  );
}

export function fromFloating(f: Date): Date {
  return new Date(
    f.getUTCFullYear(),
    f.getUTCMonth(),
    f.getUTCDate(),
    f.getUTCHours(),
    f.getUTCMinutes(),
    f.getUTCSeconds(),
  );
}

export function stripRulePrefix(s: string): string {
  return s.replace(/^RRULE:/, '');
}

export function ruleFor(rrule: string, start: string): RRule {
  const opts = RRule.parseString(stripRulePrefix(rrule));
  opts.dtstart = toFloating(new Date(start));
  return new RRule(opts);
}

export interface Occurrence {
  /** Unique key: `${itemId}|${originalStart}` (or the item id for one-off items). */
  key: string;
  item: Item;
  /** Start of the occurrence as generated by the series (identity of the occurrence). */
  originalStart: string;
  start: string;
  end: string;
  allDay: boolean;
  title: string;
  notes?: string;
  recurring: boolean;
  done: boolean;
  overridden: boolean;
}

export interface Range {
  start: Date;
  end: Date;
}

const HOUR = 3_600_000;
const DAY = 24 * HOUR;

/** Duration of an item in ms (sensible defaults when `end` is missing). */
export function itemDuration(item: Item): number {
  if (!item.start) return 0;
  if (item.end) return Math.max(0, Date.parse(item.end) - Date.parse(item.start));
  if (item.kind === 'deadline') return 0;
  return item.allDay ? DAY : HOUR;
}

/** End of an occurrence starting at `start`. All-day items keep whole days across DST. */
export function occurrenceEnd(item: Item, start: Date): Date {
  const dur = itemDuration(item);
  if (item.allDay) {
    const days = Math.max(item.kind === 'deadline' ? 0 : 1, Math.round(dur / DAY));
    const e = new Date(start);
    e.setDate(e.getDate() + days);
    return e;
  }
  return new Date(start.getTime() + dur);
}

function overlaps(start: number, end: number, range: Range): boolean {
  const s = range.start.getTime();
  const e = range.end.getTime();
  // Zero-length items (deadlines) count if their start lies inside the range.
  if (end === start) return start >= s && start < e;
  return start < e && end > s;
}

/** All original starts (ISO) of a recurring item between two instants (inclusive). */
export function seriesStartsBetween(item: Item, from: Date, to: Date): string[] {
  if (!item.rrule || !item.start) return [];
  const rule = ruleFor(item.rrule, item.start);
  return rule.between(toFloating(from), toFloating(to), true).map((f) => fromFloating(f).toISOString());
}

/** True when a recurring item has no occurrences left after `now`. */
export function seriesEnded(item: Item, now: Date): boolean {
  if (!item.rrule || !item.start) return false;
  return ruleFor(item.rrule, item.start).after(toFloating(now), true) === null;
}

/** Whether `iso` is a start generated by the series (ignoring exdates). */
export function isSeriesStart(item: Item, iso: string): boolean {
  const d = new Date(iso);
  return seriesStartsBetween(item, d, d).length > 0;
}

/**
 * Expand items into concrete occurrences overlapping `range`.
 * Applies exdates, overrides (moves, edits, cancellations) and completions.
 */
export function expandOccurrences(
  items: Item[],
  overrides: Override[],
  completions: Completion[],
  range: Range,
): Occurrence[] {
  const ovByItem = new Map<string, Map<string, Override>>();
  for (const o of overrides) {
    let m = ovByItem.get(o.itemId);
    if (!m) ovByItem.set(o.itemId, (m = new Map()));
    m.set(o.originalStart, o);
  }
  const doneSet = new Set(completions.map((c) => `${c.itemId}|${c.occurrenceStart}`));

  const out: Occurrence[] = [];
  for (const item of items) {
    if (!item.start) continue; // unscheduled to-do

    if (!item.rrule) {
      const end = item.end ?? occurrenceEnd(item, new Date(item.start)).toISOString();
      if (overlaps(Date.parse(item.start), Date.parse(end), range)) {
        out.push({
          key: item.id,
          item,
          originalStart: item.start,
          start: item.start,
          end,
          allDay: item.allDay,
          title: item.title,
          notes: item.notes,
          recurring: false,
          done: !!item.done,
          overridden: false,
        });
      }
      continue;
    }

    const dur = itemDuration(item);
    const exdates = new Set(item.exdates);
    const ovs = ovByItem.get(item.id) ?? new Map<string, Override>();
    // Widen the window so occurrences that started before the range but still run into it are included.
    const from = new Date(range.start.getTime() - dur - DAY);
    const starts = new Set(seriesStartsBetween(item, from, range.end));
    // Occurrences moved into the range from outside it.
    for (const [orig, ov] of ovs) {
      if (starts.has(orig) || ov.cancelled || !ov.start) continue;
      const s = Date.parse(ov.start);
      const e = Date.parse(ov.end ?? new Date(s + dur).toISOString());
      if (overlaps(s, e, range) && isSeriesStart(item, orig)) starts.add(orig);
    }

    for (const orig of starts) {
      if (exdates.has(orig)) continue;
      const ov = ovs.get(orig);
      if (ov?.cancelled) continue;
      const start = ov?.start ?? orig;
      const end = ov?.end ?? (ov?.start ? new Date(Date.parse(ov.start) + dur).toISOString() : occurrenceEnd(item, new Date(orig)).toISOString());
      if (!overlaps(Date.parse(start), Date.parse(end), range)) continue;
      out.push({
        key: `${item.id}|${orig}`,
        item,
        originalStart: orig,
        start,
        end,
        allDay: item.allDay,
        title: ov?.title ?? item.title,
        notes: ov?.notes ?? item.notes,
        recurring: true,
        done: doneSet.has(`${item.id}|${orig}`),
        overridden: !!ov,
      });
    }
  }
  out.sort((a, b) => a.start.localeCompare(b.start) || a.title.localeCompare(b.title));
  return out;
}

