/* ------------------------------------------------------------------ */

/** End a series just before `beforeIso` (local instant). Clears COUNT. */
export function withUntilBefore(rrule: string, beforeIso: string): string {
  const o = RRule.parseString(stripRulePrefix(rrule));
  delete o.count;
  o.until = new Date(toFloating(new Date(beforeIso)).getTime() - 1000);
  return stripRulePrefix(RRule.optionsToString(o));
}

/** Replace COUNT in a rule (or leave it untouched when the rule has none). */
export function withCount(rrule: string, count: number | undefined): string {
  const o = RRule.parseString(stripRulePrefix(rrule));
  if (count === undefined) delete o.count;
  else o.count = count;
  return stripRulePrefix(RRule.optionsToString(o));
}

export function ruleCount(rrule: string): number | undefined {
  return RRule.parseString(stripRulePrefix(rrule)).count ?? undefined;
}
